/**
 * Writes `src/app/[lang]/<route>/page.tsx` for every English page that does
 * not have one: the same page, rendered with the request's language set. See
 * `lib/i18n` and `lib/request-locale`. Re-run after adding a page.
 */
const fs = require('fs');
const path = require('path');

const SKIP = [/^bubble\/panel/, /^tier-list\/(ranked|trophy)/, /^tier-list\/page/, /^brawlers\/\[slug\]\/counters/];
const root = 'src/app';
const pages = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) { if (!['[lang]', 'api'].includes(e.name)) walk(p); }
    else if (e.name === 'page.tsx') pages.push(p);
  }
})(root);

let made = 0;
for (const file of pages) {
  const rel = path.relative(root, file).replace(/\\/g, '/');
  if (SKIP.some((re) => re.test(rel))) continue;
  const out = path.join(root, '[lang]', rel);
  const src = fs.readFileSync(file, 'utf8');
  const route = rel.replace(/\/?page\.tsx$/, '');
  const imp = `@/app/${route ? route + '/' : ''}page`;

  const revalidate = src.match(/^export const revalidate = ([^;]+);/m)?.[1];
  const dynamic = src.match(/^export const dynamic = ([^;]+);/m)?.[1];
  const hasGM = /^export (async )?function generateMetadata/m.test(src);
  const gmArgs = /^export (async )?function generateMetadata\s*\(\s*\)/m.test(src) ? '' : 'props as never';
  const hasMD = /^export const metadata\b/m.test(src);
  const def = src.match(/^export default (async )?function \w*\s*\(([^)]*)\)/m);
  const takesProps = def && def[2].trim() !== '';
  const dynamicSeg = /\[/.test(route);

  const lines = [];
  lines.push(`import type { Metadata } from 'next';`);
  lines.push(`import { notFound } from 'next/navigation';`);
  lines.push('');
  const named = [hasGM && 'generateMetadata as englishMetadata', hasMD && 'metadata as englishMetadata'].filter(Boolean);
  lines.push(`import EnglishPage${named.length ? `, { ${named[0]} }` : ''} from '${imp}';`);
  lines.push(`import { isIntlLocale } from '@/lib/i18n';`);
  if (named.length) lines.push(`import { routePath, translateMetadata } from '@/lib/i18n-metadata';`);
  lines.push(`import { setRequestLocale } from '@/lib/request-locale';`);
  lines.push('');
  lines.push(`/* \`/${route}\` in Spanish or Portuguese: the English page with the language set (see lib/i18n). Generated by scripts/i18n-wrappers.cjs. */`);
  if (revalidate) lines.push(`export const revalidate = ${revalidate};`);
  if (dynamic) lines.push(`export const dynamic = ${dynamic};`);
  // A page rendered per request in English (live API reads, no cache) stays
  // that way: an empty generateStaticParams would make it ISR, and Next then
  // refuses its no-store fetches at runtime. Static pages keep runtime ISR.
  const hasGSP = /^export (async )?function generateStaticParams/m.test(src);
  const perRequest = dynamic === "'force-dynamic'" || (dynamicSeg && !revalidate && !hasGSP);
  if (!perRequest) {
    lines.push('');
    lines.push('/* Runtime ISR: AGENTS.md trap 1. */');
    lines.push('export async function generateStaticParams() {');
    lines.push('  return [];');
    lines.push('}');
  }
  lines.push('');
  lines.push(`type Props = { params: Promise<{ lang: string }> } & Record<string, unknown>;`);
  lines.push('');
  lines.push(`async function language(props: Props) {`);
  lines.push(`  const { lang } = await props.params;`);
  lines.push(`  if (!isIntlLocale(lang)) notFound();`);
  lines.push(`  setRequestLocale(lang);`);
  lines.push(`  return lang;`);
  lines.push(`}`);
  if (named.length) {
    lines.push('');
    lines.push(`export async function generateMetadata(props: Props): Promise<Metadata> {`);
    lines.push(`  const lang = await language(props);`);
    lines.push(`  const path = routePath('/${route}', (await props.params) as Record<string, string | string[]>);`);
    if (hasGM) lines.push(`  return translateMetadata(await englishMetadata(${gmArgs}), lang, path);`);
    else lines.push(`  return translateMetadata(englishMetadata, lang, path);`);
    lines.push(`}`);
  }
  lines.push('');
  lines.push(`export default async function IntlPage(props: Props) {`);
  lines.push(`  await language(props);`);
  // Called rather than rendered as <EnglishPage {...props} />: the English
  // page's props type names its own params, which this route only extends.
  lines.push(takesProps ? `  return EnglishPage(props as never);` : `  return <EnglishPage />;`);
  lines.push(`}`);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, lines.join('\n') + '\n');
  made++;
  if (dynamicSeg && /dynamicParams = false/.test(src)) console.log(`note: ${rel} has dynamicParams = false; the copy renders any param and relies on the page's own notFound()`);
}
console.log(`${made} wrappers written`);
